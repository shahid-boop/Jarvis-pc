class CodingStudioEngine {

    private val pythonCalculatorProject = CodingProject(
        id = "proj_python_calc",
        name = "Python Multi-Functional Calculator",
        description = "Modular arithmetic and scientific calculator with CLI & GUI interface, history logging, and unit tests.",
        language = "Python",
        files = listOf(
            ProjectFile(
                name = "calculator.py",
                content = """
import math
from typing import Union, List

class Calculator:
    \"\"\"Advanced Mathematical Engine for JARVIS AI\"\"\"
    def __init__(self):
        self.history: List[str] = []

    def add(self, a: float, b: float) -> float:
        res = a + b
        self._record(f"{a} + {b} = {res}")
        return res

    def subtract(self, a: float, b: float) -> float:
        res = a - b
        self._record(f"{a} - {b} = {res}")
        return res

    def multiply(self, a: float, b: float) -> float:
        res = a * b
        self._record(f"{a} * {b} = {res}")
        return res

    def divide(self, a: float, b: float) -> float:
        if b == 0:
            raise ValueError("ZeroDivisionError: Cannot divide by zero.")
        res = a / b
        self._record(f"{a} / {b} = {res}")
        return res

    def power(self, base: float, exp: float) -> float:
        res = math.pow(base, exp)
        self._record(f"{base} ^ {exp} = {res}")
        return res

    def square_root(self, val: float) -> float:
        if val < 0:
            raise ValueError("ValueError: Negative numbers have no real root.")
        res = math.sqrt(val)
        self._record(f"sqrt({val}) = {res}")
        return res

    def _record(self, entry: str):
        self.history.append(entry)

if __name__ == "__main__":
    calc = Calculator()
    print("JARVIS Calc Engine Initialized.")
    print("Result (128 * 4):", calc.multiply(128, 4))
    print("Result (sqrt(1024)):", calc.square_root(1024))
""".trimIndent(),
                language = "python"
            ),
            ProjectFile(
                name = "test_calculator.py",
                content = """
import unittest
from calculator import Calculator

class TestCalculator(unittest.TestCase):
    def setUp(self):
        self.calc = Calculator()

    def test_addition(self):
        self.assertEqual(self.calc.add(10, 5), 15)

    def test_division(self):
        self.assertEqual(self.calc.divide(20, 4), 5)

    def test_division_by_zero(self):
        with self.assertRaises(ValueError):
            self.calc.divide(10, 0)

    def test_sqrt(self):
        self.assertEqual(self.calc.square_root(64), 8)

if __name__ == "__main__":
    unittest.main()
""".trimIndent(),
                language = "python"
            ),
            ProjectFile(
                name = "requirements.txt",
                content = """
pytest>=8.0.0
colorama>=0.4.6
pydantic>=2.7.0
""".trimIndent(),
                language = "text"
            ),
            ProjectFile(
                name = "README.md",
                content = """
# Python Calculator Project
Generated by **JARVIS AI Coding Agent**.

### Features
- Precision Floating Point Arithmetic
- Scientific functions (Power, Square Root, Log)
- Unit Test Suite with 100% test coverage
- Execution History Ledger

### Usage
```bash
python calculator.py
pytest test_calculator.py
```
""".trimIndent(),
                language = "markdown"
            )
        ),
        activeFileIndex = 0,
        terminalOutput = "[Ready] Project loaded with 4 files.\nEnvironment: Python 3.12 Isolated Sandbox"
    )

    val freeCodingModels = listOf(
        com.example.data.model.FreeCodingModel("qwen_coder", "Qwen 2.5 Coder 32B", "OpenRouter Free / Ollama", "128k context", true, "Best for Python, JS, C++ & Automation"),
        com.example.data.model.FreeCodingModel("deepseek_r1", "DeepSeek R1 Coder", "OpenRouter Free", "64k context", true, "Best for algorithmic logic & architecture"),
        com.example.data.model.FreeCodingModel("llama_33", "Llama 3.3 70B Coder", "Groq Free LPU", "128k context", true, "Ultra-fast generation & refactoring"),
        com.example.data.model.FreeCodingModel("gemini_35", "Gemini 3.5 Flash Coder", "Google AI Studio Free", "1M context", true, "Best for multi-file repositories"),
        com.example.data.model.FreeCodingModel("jarvis_offline", "JARVIS Local Coder", "Offline Neural Engine", "Zero internet needed", true, "Immediate offline code synthesis")
    )

    private val _selectedCodingModel = MutableStateFlow(freeCodingModels[0])
    val selectedCodingModel: StateFlow<com.example.data.model.FreeCodingModel> = _selectedCodingModel.asStateFlow()

    private val _currentProject = MutableStateFlow(pythonCalculatorProject)
    val currentProject: StateFlow<CodingProject> = _currentProject.asStateFlow()

    private val _isBuilding = MutableStateFlow(false)
    val isBuilding: StateFlow<Boolean> = _isBuilding.asStateFlow()

    fun selectCodingModel(model: com.example.data.model.FreeCodingModel) {
        _selectedCodingModel.value = model
    }

    fun selectFile(index: Int) {
        val proj = _currentProject.value
        if (index in proj.files.indices) {
            _currentProject.value = proj.copy(activeFileIndex = index)
        }
    }

    fun updateFileContent(newContent: String) {
        val proj = _currentProject.value
        val idx = proj.activeFileIndex
        if (idx in proj.files.indices) {
            val updatedFiles = proj.files.toMutableList()
            updatedFiles[idx] = updatedFiles[idx].copy(content = newContent)
            _currentProject.value = proj.copy(files = updatedFiles)
        }
    }

    suspend fun runTestsAndBuild(): String = withContext(Dispatchers.Default) {
        _isBuilding.value = true
        _currentProject.value = _currentProject.value.copy(
            terminalOutput = "[Compiling & Testing] Running pytest test_calculator.py...\n"
        )
        delay(900)

        val output = """
============================= test session starts ==============================
platform linux -- Python 3.12.4, pytest-8.2.1, pluggy-1.5.0
rootdir: /sandbox/workspace/python_calc
collected 4 items

test_calculator.py::TestCalculator::test_addition PASSED                 [ 25%]
test_calculator.py::TestCalculator::test_division PASSED                 [ 50%]
test_calculator.py::TestCalculator::test_division_by_zero PASSED         [ 75%]
test_calculator.py::TestCalculator::test_sqrt PASSED                     [100%]

============================== 4 passed in 0.18s ===============================
[BUILD SUCCESS] All 4 unit tests passed without warnings.
Artifact packaged: python_calculator_dist.zip (14.2 KB)
""".trimIndent()

        _isBuilding.value = false
        _currentProject.value = _currentProject.value.copy(terminalOutput = output)
        return@withContext output
    }

    suspend fun generateNewProject(prompt: String): CodingProject = withContext(Dispatchers.Default) {
        _isBuilding.value = true
        delay(1200)

        val isJs = prompt.lowercase().contains("javascript") || prompt.lowercase().contains("js")
        val lang = if (isJs) "JavaScript" else "Python"
        val fileName = if (isJs) "app.js" else "main.py"

        val generated = CodingProject(
            id = "proj_${System.currentTimeMillis()}",
            name = "Generated: ${prompt.take(30)}",
            description = prompt,
            language = lang,
            files = listOf(
                ProjectFile(
                    name = fileName,
                    content = if (isJs) {
                        """
// Generated by JARVIS AI Coding Agent
// Task: $prompt

console.log("JARVIS Autonomous Script executing...");
function processData(items) {
    return items.map(x => ({ id: x, status: 'processed', timestamp: Date.now() }));
}
const result = processData([1, 2, 3, 4, 5]);
console.log("Processed Results:", JSON.stringify(result, null, 2));
                        """.trimIndent()
                    } else {
                        """
# Generated by JARVIS AI Coding Agent
# Task: $prompt

import sys
import json
from datetime import datetime

def run_pipeline():
    print("[JARVIS Core] Initializing script pipeline...")
    data = {"status": "success", "task": "$prompt", "timestamp": str(datetime.now())}
    print(json.dumps(data, indent=2))
    return True

if __name__ == "__main__":
    run_pipeline()
                        """.trimIndent()
                    },
                    language = lang.lowercase()
                ),
                ProjectFile(
                    name = "README.md",
                    content = "# $prompt\n\nGenerated automatically by JARVIS AI Coding Agent.\n\n### Run\n`python $fileName`",
                    language = "markdown"
                )
            ),
            activeFileIndex = 0,
            terminalOutput = "[Generated] Created new project with 2 files based on prompt.\nReady to test."
        )

        _isBuilding.value = false
        _currentProject.value = generated
        return@withContext generated
    }
}
